const LEADING_DAY_OR_TIME =
  /^(?:(?:mon|tue|wed|thu|fri|monday|tuesday|wednesday|thursday|friday)\s*[:–-]\s*|\d{1,2}:\d{2}\s*(?:am|pm)?\s*[:–-]\s*)/i;

const NON_TASK_LINE_RE =
  /^(?:arrived\s+(?:at|in|on)\b|got\s+to\s+(?:the\s+)?office\b|entered\s+(?:the\s+)?office\b|went\s+(?:to\s+(?:the\s+)?office|home|back\s+to|to\s+sleep)\b|left\s+(?:the\s+office|for\s+home|at)\b|departed\b|dismissed\s+(?:at|early|around|by)\b|wrapped\s+up\s+for\s+the\s+day\b|clocked\s+(?:in|out)\b|timed\s+(?:in|out)\b|logged\s+(?:in|out)\b|signed\s+(?:in|out)\b|took\s+(?:a\s+)?(?:lunch|break|dinner|snack)\b|had\s+(?:lunch|breakfast|dinner|snack)\b|commuted\b|heading\s+home\b|returned\s+to\s+(?:the\s+)?(?:boarding|bh|home)\b|stayed\s+at\s+(?:boarding\s+house|home)\b|(?:pumasok|umuuwi|umuwi|uwian|nag-?lunch|kumain)\b)/i;

const TRAILING_ATTENDANCE_RE =
  /(?:[,;]\s*(?:and\s+)?(?:left|arrived|went\s+home|dismissed|departed|clocked\s+(?:in|out)|timed\s+(?:in|out)|signed\s+(?:in|out))\b[^.;]*|\s+(?:before\s+going\s+home|before\s+dismissal|until\s+\d{1,2}(?::\d{2})?\s*(?:am|pm)))\s*$/i;

